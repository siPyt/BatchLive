function fixture(run) {
  const before = { store: useStore.getState(), security: useSecurity.getState(), window: global.window }
  const alerts = [], db = new Map()
  global.window = { alert: message => alerts.push(message), localStorage: {
    setItem: (k, v) => db.set(k, v), getItem: k => db.get(k) ?? null
  } }
  try {
    useSecurity.setState({ currentUser: 'admin', locked: false })
    const s = useStore.getState()
    s.newProject('blank')
    useStore.setState({ running: true })
    for (const [tag, type] of [['XVSTAT-101', 'DI'], ['LI-101', 'AI']]) s.createModule({ tag, type, area: 'FEED', description: tag })
    s.createController('CTLR', 'Motor template')
    s.commissionController('CTLR')
    for (const [slot, type, dst] of [[3, 'DI', 'XI-2'], [4, 'DO', 'ZX-2'], [1, 'AI', 'LI-IN'], [2, 'DI', 'XV-IN']]) {
      s.addTraditionalCard('CTLR', slot, type)
      s.configureTraditionalChannel(`CTLR/C0${slot}`, 2, { dst, enabled: true })
    }
    s.bindAnalogDst('LI-101', 'input', 'LI-IN')
    s.bindDiscreteDst('XVSTAT-101', 'XV-IN')
    s.setTraditionalInput('LI-IN', 70)
    s.setTraditionalInput('XV-IN', 1)
    s.tick(.1)
    assert.equal(s.createMotorTemplate('MTR-102', 'FEED'), true)
    s.setFbInput('MTR-102/CND1', 'in1', { kind: 'ref', tag: 'XVSTAT-101', value: 0 })
    s.setFbInput('MTR-102/CND2', 'in1', { kind: 'ref', tag: 'LI-101', value: 0 })
    s.editDeviceDraft('MTR-102', { controllerTag: 'CTLR', inputDst: 'XI-2', outputDst: 'ZX-2' })
    run(s, alerts, db)
  } finally {
    useStore.setState(before.store, true)
    useSecurity.setState(before.security, true)
    if (before.window === undefined) delete global.window
    else global.window = before.window
  }
}
function motor() { return useStore.getState().modules['MTR-102'] }
function block(name) { return motor().ownedBlocks[name] }
function record() { return useStore.getState().deviceLifecycle['MTR-102'] }
function deploy(s) {
  assert.equal(s.saveDeviceConfiguration('MTR-102'), true)
  assert.equal(s.downloadDeviceConfiguration('MTR-102'), true)
  s.tick(.1)
}
test('template copy creates one owning motor, namespaced owned graph and inhibited offline draft, not independent live modules', () => fixture(s => {
  assert.equal(motor().templateId, 'MTR-11_ILOCK')
  assert.deepEqual(Object.keys(motor().ownedBlocks), ['CND1', 'CND2', 'BFI1', 'OR1', 'NOT1', 'AND1'])
  assert.equal(useStore.getState().modules['MTR-102/CND1'], undefined)
  s.tick(.1)
  assert.equal(block('CND1').bad, true)
  assert.equal(motor().downloaded, false)
  const view = deviceEditorModules(useStore.getState().modules, useStore.getState().deviceLifecycle)
  const connected = connectedModuleTags(view, 'MTR-102')
  for (const tag of ['MTR-102/CND1', 'MTR-102/CND2', 'MTR-102/BFI1', 'MTR-102/OR1', 'MTR-102/NOT1', 'MTR-102/AND1', 'XVSTAT-101', 'LI-101']) assert.ok(connected.includes(tag))
  const diagram = buildControlDiagram(connected, view)
  assert.ok(diagram.wires.some(w => w.fromTag === 'MTR-102/NOT1' && w.toTag === 'MTR-102' && w.which === 'ilk'))
  assert.ok(diagram.wires.some(w => w.fromTag === 'MTR-102/AND1' && w.toTag === 'MTR-102' && w.which === 'permissive'))
  assert.ok(diagram.wires.some(w => w.fromTag === 'MTR-102/CND1' && w.toTag === 'MTR-102/OR1'))
}))
test('saved owned configuration excludes live trap/timers; offline edits are isolated and Full deploy transfers together', () => fixture((s, _, db) => {
  s.setFbConfig('MTR-102/CND2', { expr: 'IN1 < 49', delaySec: 3 })
  assert.equal(record().draft.strategy.CND2.expr, 'IN1 < 49')
  assert.equal(block('CND2').expr, 'IN1 < 50')
  deploy(s)
  assert.equal(block('CND2').expr, 'IN1 < 49')
  assert.equal(block('CND2').delaySec, 3)
  const saved = parseDevice(db.get(savedDeviceKey('MTR-102')), 'MTR-102')
  assert.equal(saved.strategy.CND2.in1.tag, 'LI-101')
  assert.equal(saved.strategy.BFI1.firstOut, undefined)
  assert.equal(saved.strategy.CND2._timerElapsed, undefined)
  s.setDeviceOnline('MTR-102', false)
  s.setFbConfig('MTR-102/CND2', { delaySec: 9 })
  assert.equal(block('CND2').delaySec, 3)
  assert.equal(record().saved.strategy.CND2.delaySec, 3)
  assert.equal(record().deployed.strategy.CND2.delaySec, 3)
  s.loadDeviceConfiguration('MTR-102')
  assert.equal(record().draft.strategy.CND2.delaySec, 3)
}))
