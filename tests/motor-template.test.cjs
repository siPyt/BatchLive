test('owned references validate atomically, online config rejects and blocks cannot be deleted independently', () => fixture((s, alerts) => {
  const before = JSON.stringify(record().draft.strategy)
  s.setFbInput('MTR-102/CND1', 'in1', { kind: 'ref', tag: 'MISSING', value: 0 })
  s.setFbConfig('MTR-102/CND2', { expr: 'IN1 <', delaySec: 4 })
  assert.equal(JSON.stringify(record().draft.strategy), before)
  deploy(s)
  s.setFbConfig('MTR-102/CND2', { delaySec: 6 })
  assert.equal(block('CND2').delaySec, 4)
  s.deleteModule('MTR-102/CND1')
  assert.ok(block('CND1'))
  assert.match(alerts.at(-1), /Owned template blocks/)
  s.deleteModule('MTR-102')
  assert.equal(motor(), undefined)
  assert.equal(useStore.getState().deviceLifecycle['MTR-102'], undefined)
}))
